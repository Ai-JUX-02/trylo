/**
 * 源① 的门槛：**同一个工具**在本 run 内失败几次才算「这工具不行」。
 *
 * 注意它数的是工具维度（一个工具坏了几次），与 `gap-detector` 的
 * `repeatThreshold`（同一个 taskFamily+capability 组里坏了几条 observation，
 * 事维度）是**两个量**。两者数值撞在一起是巧合，不是同一件事——正因为它们不同，
 * 「工具 Y 老用错」和「这类事没人干得了」才能被分开，决策树的两支才有依据。
 */
export const TOOL_FAILURE_THRESHOLD = 3;

/** 同一提议的冷却期（规格 §5，7 天）。 */
export const PROPOSAL_COOLDOWN_MS = 7 * 24 * 60 * 60 * 1000;

/** 全局每日提议上限（规格 §5）。 */
export const DAILY_PROPOSAL_LIMIT = 3;

/** 同一工具每 run 最多几条提议（规格 §5）。 */
export const PER_TOOL_PROPOSALS_PER_RUN = 1;

/**
 * 重升级（B 轨迹结晶）的门槛：同类任务要有几条**成功**轨迹才敢结晶。
 *
 * 它落在决策树里而不是结晶实现里，是因为决策树必须**总**能给出一个答案：同一个
 * 失败到了「A 已做过还在错」这一步，是换一个现成的还是自己造一个，取决于手上
 * 有没有可复用成功轨迹。TP-1 手上没有轨迹数据（B 归 TP-2），所以恒传 0，
 * 走「换 Y」那支；TP-2 接上真实计数后这一支自然活过来——决策规则不需要改。
 */
export const CRYSTAL_MIN_SUCCESSES = 2;
