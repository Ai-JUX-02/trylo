/**
 * A 描述精炼的命名常量（P05 工具学习规格 §6 + §13.2 定稿口径）。
 *
 * 与意识层同一条纪律：**这一层不许出现魔数**。阈值与收敛线全部从这里进，
 * 改口径只改这个文件，所有者一行可改。
 */

/**
 * 攒几条失败证据才值得跑一次「这描述让模型在哪用错」的分析。
 *
 * 与 `TOOL_FAILURE_THRESHOLD`（意识层源① 的门槛）**同值但不同义**，正如那个
 * 常量自己的注释所说：那里数的是「这个工具坏了几次」，这里数的是「针对这条
 * 描述攒了几条错法」。取同一个 3 是为了让两处的行为可预期——攒够意识层认为
 * 「这工具不行」的那些证据，恰好也就是够做一次描述分析的那些证据；**不是**
 * 因为它们是同一个量，所以不许写成互相 import 的一个常量。
 */
export const REFINE_MIN_EVIDENCE = 3;

/**
 * 收敛线：重写后的描述与上一版相似度超过它，就认为再精炼只是在原地打转。
 *
 * 0.75 是 DRAFT 移植过来的参数。规格同时给了退化口径——**第一版没有嵌入**
 * （不引模型、不引向量库），所以这里的相似度是字符级的：它只用来判「两版是不是
 * 几乎一样」，不用来判语义。语义层面的「还是没改好」由 §6 的退化规则兜底：
 * 只有出现**新的**失败证据才再提议一次。
 */
export const REFINE_SIMILARITY_CONVERGED = 0.75;

/**
 * 一个工具最多留几版历史。
 *
 * 留历史不是为了考古，是为了**回滚有地方可退**、以及让人审时能看见「上一版
 * 长什么样」。上限存在是因为这个 store 住在本地 app-data 里，无界增长的水落
 * 石出那天是磁盘，不是内存。
 */
export const REFINE_MAX_HISTORY = 10;

/**
 * 精炼后描述的硬上限。
 *
 * 与 MCP 原描述用的是同一个天花板（`MAX_MCP_DESCRIPTION_LENGTH`）：覆盖层换掉
 * 的是**文本**，不是这条约束——一条 5000 字的「精炼」只会把上下文挤掉，而它
 * 要解决的恰恰是「模型读不懂」。所以精炼文本超长时，截断照旧生效。
 */
export const REFINE_MAX_DESCRIPTION_LENGTH = 2048;
